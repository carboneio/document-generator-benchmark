#!/usr/bin/env node
/**
 * Turns the JSON results written by `bench/run.mjs` into:
 *   - docs/<stamp>.html      dated public report (committed)
 *   - docs/index.html        copy of the latest report
 *   - docs/archive.json      history of previous reports
 *   - RESULT.md              raw metrics of the latest campaign
 *   - results/results.csv    same data, machine readable
 *   - README.md              short summary + link to the HTML page
 *
 *   node bench/report.mjs [resultsDir]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT_DIR } from './matrix.mjs';
import { buildModel, campaignStamp, filterCampaign, renderHtml, summaryMarkdown, toRows } from './html.mjs';

const DOCS_DIR = path.join(ROOT_DIR, 'docs');
const MARKER_START = '<!-- BENCHMARK:RESULTS:START -->';
const MARKER_END = '<!-- BENCHMARK:RESULTS:END -->';
const LEGACY_START = '<!-- BENCHMARK:TABLE:START -->';
const LEGACY_END = '<!-- BENCHMARK:TABLE:END -->';

const num = (value, digits = 2) => (typeof value === 'number' && Number.isFinite(value) ? value.toFixed(digits) : 'n/a');

function readResults (resultsDir) {
  if (fs.existsSync(resultsDir) === false) {
    return { meta: null, results: [] };
  }

  const indexPath = path.join(resultsDir, 'index.json');

  if (fs.existsSync(indexPath) === true) {
    const index = JSON.parse(fs.readFileSync(indexPath, 'utf8'));

    return { meta: index.meta ?? null, results: index.results ?? [] };
  }

  const results = fs.readdirSync(resultsDir)
    .filter((file) => file.endsWith('.json') === true && file !== 'index.json')
    .map((file) => JSON.parse(fs.readFileSync(path.join(resultsDir, file), 'utf8')));

  return { meta: null, results };
}

function buildCsv (rows) {
  const header = ['Vendor', 'Sample', 'Family', 'Pages', 'Template', 'Output', 'Converter', 'Profile', 'CPU', 'VU',
    'Med(ms)', 'Avg(ms)', 'p95(ms)', 'Max(ms)', 'RPS', 'Pages/s', 'Requests', 'Failures(%)', 'Label'];
  const lines = [header.map((cell) => `"${cell}"`).join(',')];

  for (const row of rows) {
    lines.push([
      row.vendor,
      row.sample,
      row.family,
      row.pages,
      row.template,
      row.output,
      row.converter === '—' ? 'none' : row.converter,
      row.profile,
      row.cpu,
      row.vus,
      num(row.med),
      num(row.avg),
      num(row.p95),
      num(row.max),
      num(row.rps),
      num(row.rps === null ? null : row.rps * row.pages),
      row.requests,
      num(row.failures),
      row.label,
    ].map((cell) => `"${String(cell ?? '')}"`).join(','));
  }

  return `${lines.join('\n')}\n`;
}

/** The two measures of the campaign, one line for the environment table. */
function formatLoad (meta) {
  const profiles = Array.isArray(meta?.profiles) === true ? meta.profiles : [];

  if (profiles.length === 0) {
    return `${Array.isArray(meta?.vus) === true ? meta.vus.join(', ') : (meta?.vus ?? '?')} VU`;
  }

  return profiles
    .map((profile) => `${profile.renders} documents ${profile.id === 'solo' ? 'one at a time' : `× ${profile.vus} VU`} on ${profile.cpu} CPU`)
    .join(' · ');
}

const GROUP_ORDER = ['merge', 'I', 'L', 'O', 'C'];

/**
 * Keeps both measures of the same pipeline together, so two campaigns can be
 * diffed line by line.
 */
function byPipeline (a, b) {
  const rank = (row) => [
    row.family,
    row.raw.templateExt,
    String(GROUP_ORDER.indexOf(row.raw.group)),
    String(row.pages).padStart(6, '0'),
    row.profile === 'solo' ? '0' : '1',
    String(row.cpu).padStart(3, '0'),
    String(row.vus).padStart(4, '0'),
  ].join('|');

  return rank(a).localeCompare(rank(b));
}

function buildResultMd (rows, meta) {
  const parts = ['RESULT', '======', ''];

  parts.push('Generated by `npm run bench` — latest campaign only, skipped / stale VU runs omitted.', '');

  if (rows.length === 0) {
    parts.push('No measured run in the latest campaign. Execute `npm run bench`.', '');

    return parts.join('\n');
  }

  if (meta !== null) {
    parts.push('## Test environment', '');
    parts.push('| Item | Value |', '| ---- | ----- |');
    parts.push(`| Date | ${meta.finishedAt ?? meta.startedAt ?? 'unknown'} |`);
    parts.push(`| Carbone image | \`${meta.image}\` |`);
    parts.push(`| Factories (CPU) | ${(meta.cpus ?? []).join(', ')} |`);
    parts.push(`| Load | ${formatLoad(meta)} |`);
    parts.push(`| Host | ${meta.host?.cpu ?? 'unknown'} — ${meta.host?.cores ?? '?'} cores, ${meta.host?.memory ?? '?'} |`);
    parts.push(`| OS | ${meta.host?.platform ?? 'unknown'} |`);
    parts.push(`| k6 | ${meta.k6 ?? 'unknown'} |`);
    parts.push(`| Docker | ${meta.docker ?? 'unknown'} |`);
    parts.push('');
  }

  parts.push('## Detailed metrics', '');

  for (const row of [...rows].sort(byPipeline)) {
    const latency = row.raw.metrics.latency;
    const pagesPerSecond = row.rps === null ? null : row.rps * row.pages;

    parts.push(`### ${row.label}`, '');
    parts.push(`- vendor: \`${row.vendor}\``);
    parts.push(`- template: \`${row.raw.templateFile}\``);
    parts.push(`- data: \`${row.raw.dataFile ?? '{}'}\``);
    parts.push(`- pages: ${row.pages}`);
    parts.push(`- request: \`convertTo: ${row.raw.convertTo ?? 'none'}\`, \`converter: ${row.raw.converter ?? 'none'}\`, \`factories: ${row.cpu}\`, \`vus: ${row.vus}\``);
    parts.push(`- profile: \`${row.profile}\`, ${row.raw.renders ?? '?'} renders per VU, up to \`${row.raw.maxDuration ?? '?'}\``);
    parts.push('');
    parts.push('```');
    parts.push(`documents ..........: ${row.requests}`);

    // Under load the rate is the result; alone it is the time of one document
    if (row.raw.outOfScale === true) {
      parts.push(`out of scale .......: no document within ${row.raw.timeout ?? '?'}`);
    } else if (row.profile === 'solo') {
      parts.push(`one document .......: ${num(row.med)} ms, ${num(pagesPerSecond)} pages/s`);
    } else {
      parts.push(`throughput .........: ${num(row.rps)} doc/s, ${num(row.rps === null ? null : row.rps * 60, 0)} doc/min, ${num(pagesPerSecond)} pages/s`);
    }

    parts.push(`failures ...........: ${num(row.failures)} %`);
    parts.push(`latency ............: avg=${num(latency.avg)}ms min=${num(latency.min)}ms med=${num(latency.med)}ms max=${num(latency.max)}ms p(90)=${num(latency.p90)}ms p(95)=${num(latency.p95)}ms p(99)=${num(latency.p99)}ms`);
    parts.push('```');
    parts.push('');
  }

  return parts.join('\n');
}

function replaceMarker (readme, start, end, content) {
  const from = readme.indexOf(start);
  const to = readme.indexOf(end);

  if (from === -1 || to === -1 || to < from) {
    return null;
  }

  return `${readme.slice(0, from + start.length)}\n${content}\n${readme.slice(to)}`;
}

function updateReadme (readmePath, model) {
  if (fs.existsSync(readmePath) === false) {
    return false;
  }

  const readme = fs.readFileSync(readmePath, 'utf8');
  const content = summaryMarkdown(model, {
    pageHref    : 'docs/index.html',
    archiveHref : 'docs/index.html#history',
  });

  const updated = replaceMarker(readme, MARKER_START, MARKER_END, content)
    ?? replaceMarker(readme, LEGACY_START, LEGACY_END, content);

  if (updated === null) {
    return false;
  }

  fs.writeFileSync(readmePath, updated);

  return true;
}

function readArchive () {
  const archivePath = path.join(DOCS_DIR, 'archive.json');

  if (fs.existsSync(archivePath) === false) {
    return [];
  }

  try {
    return JSON.parse(fs.readFileSync(archivePath, 'utf8'));
  } catch {
    return [];
  }
}

function writeArchive (archive) {
  fs.writeFileSync(path.join(DOCS_DIR, 'archive.json'), `${JSON.stringify(archive, null, 2)}\n`);
}

function removeLegacyCharts () {
  for (const file of ['result.svg', 'result-docx.svg', 'result-html.svg']) {
    const target = path.join(ROOT_DIR, file);

    if (fs.existsSync(target) === true) {
      fs.rmSync(target);
    }
  }
}

function writeHtmlCampaign (model) {
  fs.mkdirSync(DOCS_DIR, { recursive: true });

  const currentId = campaignStamp(model.meta);
  const filename = `${currentId}.html`;
  const archive = readArchive().filter((entry) => entry.id !== currentId);

  archive.unshift({
    id        : currentId,
    file      : filename,
    date      : model.meta?.finishedAt || model.meta?.startedAt || new Date().toISOString(),
    image     : model.meta?.image || null,
    measured  : model.measured,
    templates : model.templates.length,
  });

  const html = renderHtml({ model, archive, currentId });

  fs.writeFileSync(path.join(DOCS_DIR, filename), html);
  fs.writeFileSync(path.join(DOCS_DIR, 'index.html'), html);
  writeArchive(archive);

  return { filename, archive };
}

/* -------------------------------------------------------------------- main */

export function generateReport ({ resultsDir = path.join(ROOT_DIR, 'results') } = {}) {
  const { meta, results } = readResults(resultsDir);
  const rows = filterCampaign(toRows(results), meta);
  const model = buildModel(rows, meta);

  const csvPath = path.join(resultsDir, 'results.csv');
  const resultMdPath = path.join(ROOT_DIR, 'RESULT.md');
  const readmePath = path.join(ROOT_DIR, 'README.md');

  fs.mkdirSync(resultsDir, { recursive: true });
  fs.writeFileSync(csvPath, buildCsv(rows));
  fs.writeFileSync(resultMdPath, buildResultMd(rows, meta));

  const { filename } = writeHtmlCampaign(model);
  const readmeUpdated = updateReadme(readmePath, model);

  removeLegacyCharts();

  process.stdout.write([
    '',
    'Report generated:',
    `  - docs/${filename}`,
    '  - docs/index.html',
    '  - docs/archive.json',
    `  - ${path.relative(ROOT_DIR, resultMdPath)}`,
    `  - ${path.relative(ROOT_DIR, csvPath)}`,
    readmeUpdated === true ? '  - README.md (summary + link)' : '  - README.md skipped (BENCHMARK markers not found)',
    '',
  ].join('\n'));

  return { rows, meta, model };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateReport({ resultsDir: path.resolve(ROOT_DIR, process.argv[2] || 'results') });
}
